public class Grid {
	 public static void main(String[] args) {
	        
		int ValueA = 6;
	    int ValueB = 3;

	    for (int i = 0; i < ValueA; i++) 
	    {
	    for (int j = 0; j < ValueB; j++) 
	    {
	     System.out.print(" * ");
	    }
	    System.out.println(); 
	    }
	 }
}
